"""
Assess paced querying using actual telemetry, monitor logs,
and persisted finding state.

No traffic is generated by this script.
"""

import json
import sqlite3
from contextlib import closing
from datetime import datetime, timedelta
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import ProxyHandler, Request, build_opener

from src.detection.catalog import QUERY_VOLUME_RULE
from src.detection.evaluation import (
    assess_monitor_coverage,
    peak_window_count,
)
from src.detection.model_access import utc_timestamp
from src.telemetry.loki import NoRedirects, collection_timestamp_ns


def overlapping_findings(path, table, event_ids):
    if not path.is_file():
        raise RuntimeError("Required monitoring database not found")

    if table not in {"findings", "finding_outbox"}:
        raise ValueError("Invalid assessment table")

    # Table names are fixed by this evaluator, never supplied by telemetry.
    query = {
        "findings": "SELECT payload_json FROM findings",
        "finding_outbox": "SELECT payload_json FROM finding_outbox",
    }[table]

    with closing(sqlite3.connect(
        path.as_uri() + "?mode=ro",
        uri=True,
    )) as connection:
        rows = connection.execute(query).fetchall()

    matching = []
    for row in rows:
        finding = json.loads(row[0])
        if (
            finding["rule_id"] == "DET-002"
            and set(finding["event_ids"]).intersection(event_ids)
        ):
            matching.append(finding["finding_id"])

    return matching


def main():
    experiment = json.loads(
        Path(
            "evidence/public/paced-replication-experiment.json"
        ).read_text(encoding="utf-8")
    )

    observations = (
        experiment["training_observations"]
        + experiment["heldout_observations"]
    )
    expected_requests = {
        observation["request_id"]
        for observation in observations
    }
    if (
        experiment["scenario"] != "paced-output-based-model-replication"
        or len(expected_requests) != 36
        or experiment["requests_completed"] != 36
    ):
        raise RuntimeError("Unexpected paced experiment report")

    started = utc_timestamp(experiment["started_at"])
    completed = utc_timestamp(experiment["completed_at"])

    parameters = urlencode({
        "query": (
            '{job="p10-security",source="gateway",provenance="live-lab"}'
            ' | json'
            ' | reason="inference_succeeded"'
            ' | caller_ref="lab-caller-reader"'
            ' | model="research-model"'
        ),
        "start": collection_timestamp_ns(started.isoformat()),
        "end": collection_timestamp_ns(
            (completed + timedelta(seconds=1)).isoformat()
        ),
        "direction": "forward",
        "limit": "500",
    })

    opener = build_opener(ProxyHandler({}), NoRedirects())
    with opener.open(
        Request(
            "http://127.0.0.1:3100/loki/api/v1/query_range?"
            + parameters
        ),
        timeout=10,
    ) as response:
        raw = response.read(1_048_577)

    if len(raw) > 1_048_576:
        raise RuntimeError("Telemetry response exceeds assessment limit")

    payload = json.loads(raw)
    if payload.get("status") != "success":
        raise RuntimeError("Loki query failed")

    records = [
        json.loads(line)
        for stream in payload["data"]["result"]
        for _, line in stream["values"]
    ]
    if len(records) >= 500:
        raise RuntimeError("Query limit reached")

    if {record["request_id"] for record in records} != expected_requests:
        raise RuntimeError("Telemetry is incomplete or mixed with other activity")

    distinct = {}
    for record in records:
        event_id = record["event_id"]
        if event_id in distinct and distinct[event_id] != record:
            raise RuntimeError("Conflicting duplicate event")
        distinct[event_id] = record

    if len(distinct) != 36:
        raise RuntimeError("Expected 36 distinct inference events")

    print("PASS: all 36 paced requests correlate to actual inference events")

    peak = peak_window_count([
        utc_timestamp(record["collected_at"])
        for record in distinct.values()
    ])
    print(f"Observed maximum requests in a 60-second window: {peak}")

    log_path = Path("evidence/public/paced-query-monitor.jsonl")
    log_bytes = log_path.read_bytes()
    if len(log_bytes) > 10_485_760:
        raise RuntimeError("Monitor log exceeds assessment limit")

    polls = []
    lines = log_bytes.decode("utf-8").splitlines()
    for index, line in enumerate(lines):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except ValueError:
            # The running monitor may be writing its final line.
            if index == len(lines) - 1:
                continue
            raise RuntimeError("Malformed monitor log") from None

        if record.get("event") == "detection_poll":
            polls.append(record)

    coverage = assess_monitor_coverage(
        polls,
        started_at=started,
        completed_at=completed,
    )

    directory = Path.home() / ".local/share/project10/monitoring"
    stored = overlapping_findings(
        directory / "findings.sqlite3",
        "findings",
        set(distinct),
    )
    outbox = overlapping_findings(
        directory / "outbox.sqlite3",
        "finding_outbox",
        set(distinct),
    )

    verified_miss = (
        peak < QUERY_VOLUME_RULE.threshold
        and coverage["coverage_complete"]
        and not coverage.get("suppression_observed", True)
        and not stored
        and not outbox
        and experiment.get("suppression_inactive_at_preflight") is True
    )

    assessment = {
        "scenario": experiment["scenario"],
        "ground_truth": experiment["ground_truth"],
        "requests_verified": len(distinct),
        "observed_peak_requests_per_60_seconds": peak,
        "rule_threshold": QUERY_VOLUME_RULE.threshold,
        "monitor_coverage": coverage,
        "matching_receiver_finding_ids": stored,
        "matching_outbox_finding_ids": outbox,
        "assessment_status": (
            "verified_selected_scenario_miss"
            if verified_miss
            else "inconclusive_or_finding_observed"
        ),
        "operational_false_negative_for_declared_scenario": (
            True if verified_miss else None
        ),
        "heldout_target_agreement": experiment["evaluation"][
            "heldout_target_agreement"
        ],
        "majority_baseline_agreement": experiment["evaluation"][
            "majority_baseline_agreement"
        ],
        "limitations": [
            "One deliberately selected paced scenario",
            "Recorded healthy polls do not prove every internal operation",
            "No complete extraction or population-level detection claim",
            "The rule can behave as specified while missing adversarial activity",
        ],
    }

    Path(
        "evidence/public/paced-query-detection-assessment.json"
    ).write_text(
        json.dumps(assessment, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(assessment, indent=2))

    if verified_miss:
        print("Paced-query assessment: verified selected-scenario miss")
    else:
        print("Paced-query assessment: inspect evidence before classification")

if __name__ == "__main__":
    main()